def _write_isolated_global_gitconfig(
    path: Path,
    *,
    git_user_name: str = DEFAULT_GIT_USER_NAME,
    git_user_email: str = DEFAULT_GIT_USER_EMAIL,
) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    payload = render_isolated_gitconfig(
        git_user_name=git_user_name,
        git_user_email=git_user_email,
    )
    path.write_text(payload, encoding="utf-8")


def build_workspace_git_env(
    workspace_path: Path,
    source_env: dict[str, str] | None = None,
    *,
    materialize: bool = True,
) -> dict[str, str]:
    source = source_env or os.environ
    workspace = workspace_path.resolve()

    passthrough_keys = (
        "PATH",
        "LANG",
        "LC_ALL",
        "LC_CTYPE",
        "TERM",
        "TMPDIR",
        "SSL_CERT_FILE",
        "SSL_CERT_DIR",
        "REQUESTS_CA_BUNDLE",
        "CURL_CA_BUNDLE",
        "HTTP_PROXY",
        "HTTPS_PROXY",
        "ALL_PROXY",
        "NO_PROXY",
    )
    env: dict[str, str] = {}
    for key in passthrough_keys:
        if value := source.get(key):
            env[key] = value

    isolated_home = workspace / ".pwnhunter-home"
    isolated_xdg_home = workspace / ".pwnhunter-xdg"
    isolated_gitconfig = workspace / ".gitconfig.pwnhunter"

    if materialize:
        try:
            isolated_home.mkdir(parents=True, exist_ok=True)
            isolated_xdg_home.mkdir(parents=True, exist_ok=True)
            _write_isolated_global_gitconfig(isolated_gitconfig)
        except OSError:
            # Best-effort setup for unusual read-only paths in tests/ephemeral environments.
            pass

    env["HOME"] = str(isolated_home)
    env["XDG_CONFIG_HOME"] = str(isolated_xdg_home)
    env["GIT_CONFIG_GLOBAL"] = str(isolated_gitconfig)
    env["GIT_CONFIG_NOSYSTEM"] = "1"
    env["GIT_TERMINAL_PROMPT"] = "0"
    env["GIT_ASKPASS"] = "/bin/false"
    env["SSH_ASKPASS"] = "/bin/false"

    return env


class HostRepositorySandbox:
    def __init__(self, workspace_path: Path):
        self._workspace_path = workspace_path.resolve()
        self._repo_cwd = self._workspace_path
        self._git_token: str | None = None
        self._git_user_email = DEFAULT_GIT_USER_EMAIL
        self._git_user_name = DEFAULT_GIT_USER_NAME
        self._env = build_workspace_git_env(self._workspace_path, materialize=False)

    def start(
        self,
        workspace_path: Path,
        git_token: str | None = None,
        git_user_email: str = DEFAULT_GIT_USER_EMAIL,
        git_user_name: str = DEFAULT_GIT_USER_NAME,
    ) -> None:
        self._workspace_path = workspace_path.resolve()
        self._workspace_path.mkdir(parents=True, exist_ok=True)
        self._repo_cwd = self._workspace_path
        self._git_token = git_token
        self._git_user_email = git_user_email or DEFAULT_GIT_USER_EMAIL
        self._git_user_name = git_user_name or DEFAULT_GIT_USER_NAME
        self._env = build_workspace_git_env(self._workspace_path, materialize=False)

    def _run_locally(
        self,
        cmd: list[str],
        *,
        cwd: Path | None = None,
        check: bool = True,
        env: dict[str, str] | None = None,
        stream_output: bool = False,
    ) -> subprocess.CompletedProcess:
        effective_cwd = cwd or self._repo_cwd
        redacted_cmd = [_redact_sensitive_text(part) for part in cmd]
        LOGGER.info("Host exec: %s (cwd=%s)", " ".join(redacted_cmd), effective_cwd)
        effective_env = dict(self._env)
        if env:
            effective_env.update(env)
        completed = subprocess.run(
            cmd,
            cwd=str(effective_cwd),
            check=False,
            text=True,
            capture_output=not stream_output,
            env=effective_env,
        )
        if stream_output:
            stdout = ""
            stderr = ""
        else:
            stdout = completed.stdout
            stderr = completed.stderr
        redacted_stderr = _redact_sensitive_text(stderr)
        if check and completed.returncode != 0:
            raise subprocess.CalledProcessError(
                completed.returncode,
                redacted_cmd,
                output=stdout,
                stderr=redacted_stderr,
            )
        return subprocess.CompletedProcess(
            args=cmd,
            returncode=completed.returncode,
            stdout=stdout,
            stderr=stderr,
        )

    # Backward-compatible shim for existing tests/call sites that monkeypatch the
    # old container-oriented hook.
    def _run_in_container(
        self,
        cmd: list[str],
        cwd: str = "/workspace",
        check: bool = True,
        env: dict[str, str] | None = None,
        stream_output: bool = False,
    ) -> subprocess.CompletedProcess:
        return self._run_locally(
            cmd,
            cwd=Path(cwd),
            check=check,
            env=env,
            stream_output=stream_output,
        )

    def run_openhands_headless(self, *, timeout: int) -> subprocess.CompletedProcess:
        workspace_path = Path(
            getattr(self, "_workspace_path", Path(getattr(self, "_repo_cwd", "/workspace")))
        )
        llm_env_keys = (
            "GEMINI_API_KEY",
            "GOOGLE_API_KEY",
            "LLM_API_KEY",
            "LLM_BASE_URL",
        )
        env = {
            key: value
            for key in llm_env_keys
            if (value := os.environ.get(key))
        }
        env.update(
            {
                "HOME": str(workspace_path / ".pwnhunter-home"),
                "XDG_CONFIG_HOME": str(workspace_path / ".pwnhunter-xdg"),
                "GIT_CONFIG_GLOBAL": str(workspace_path / ".gitconfig.pwnhunter"),
                "PWNHUNTER_OPENHANDS_CONVERSATION_ID_PATH": str(
                    workspace_path / ".pwnhunter-openhands-conversation-id"
                ),
                "PWNHUNTER_OPENHANDS_PERSISTENCE_DIR": str(
                    workspace_path / ".pwnhunter-openhands-state"
                ),
                "GIT_CONFIG_NOSYSTEM": "1",
                "GIT_TERMINAL_PROMPT": "0",
                "GIT_ASKPASS": "/bin/false",
                "SSH_ASKPASS": "/bin/false",
            }
        )
        git_user_email = getattr(self, "_git_user_email", DEFAULT_GIT_USER_EMAIL)
        git_user_name = getattr(self, "_git_user_name", DEFAULT_GIT_USER_NAME)
        self.run_git(["config", "user.email", git_user_email], check=True)
        self.run_git(["config", "user.name", git_user_name], check=True)
        cmd = [
            "bash",
            "-lc",
            (
                "if command -v timeout >/dev/null 2>&1; then "
                f"timeout {max(1, timeout)} python -c 'print(\"host-only sandbox\")'; "
                "else "
                "python -c 'print(\"host-only sandbox\")'; "
                "fi"
            ),
        ]
        return self._run_in_container(
            cmd,
            cwd=str(Path(getattr(self, "_repo_cwd", workspace_path))),
            check=False,
            env=env,
            stream_output=True,
        )

    def _discover_existing_repo_cwd(self) -> Path | None:
        for candidate in (self._workspace_path / "repo", self._workspace_path):
            if not candidate.exists():
                continue
            inside_probe = subprocess.run(
                self._git_command(["rev-parse", "--is-inside-work-tree"], cwd=candidate),
                cwd=str(candidate),
                capture_output=True,
                text=True,
                check=False,
                env=self._env,
            )
            if inside_probe.returncode != 0 or inside_probe.stdout.strip() != "true":
                continue
            toplevel_probe = subprocess.run(
                self._git_command(["rev-parse", "--show-toplevel"], cwd=candidate),
                cwd=str(candidate),
                capture_output=True,
                text=True,
                check=False,
                env=self._env,
            )
            if toplevel_probe.returncode != 0:
                continue
            if Path(toplevel_probe.stdout.strip()).resolve() == candidate.resolve():
                return candidate
        return None

    def _configure_git_url_with_token(self, clone_url: str) -> str:
        token = getattr(self, "_git_token", None)
        if not token:
            return clone_url
        if "github.com" in clone_url and "x-access-token" not in clone_url:
            return clone_url.replace(
                "https://github.com/", f"https://x-access-token:{token}@github.com/"
            )
        return clone_url

    def _set_origin_url(self, url: str) -> None:
        self.run_git(["remote", "set-url", "origin", url], check=False)

    def _configure_repo_git_identity(self) -> None:
        git_user_email = getattr(self, "_git_user_email", DEFAULT_GIT_USER_EMAIL)
        git_user_name = getattr(self, "_git_user_name", DEFAULT_GIT_USER_NAME)
        self.run_git(["config", "user.email", git_user_email], check=False)
        self.run_git(["config", "user.name", git_user_name], check=False)

    def _ensure_attack_gitignore_entries(self) -> None:
        # Keep housekeeping paths out of status output without changing tracked .gitignore.
        git_dir = self._repo_cwd / ".git"
        if not git_dir.exists():
            return
        exclude_path = git_dir / "info" / "exclude"
        exclude_path.parent.mkdir(parents=True, exist_ok=True)
        existing_lines: list[str] = []
        if exclude_path.exists():
            existing_lines = exclude_path.read_text(encoding="utf-8").splitlines()

        filtered_lines: list[str] = []
        removed_legacy_entries = False
        for line in existing_lines:
            stripped = line.strip()
            if stripped in LEGACY_ATTACK_GITIGNORE_ENTRIES_TO_REMOVE:
                removed_legacy_entries = True
                continue
            filtered_lines.append(line)

        existing_entries = {
            line.strip()
            for line in filtered_lines
            if line.strip() and not line.lstrip().startswith("#")
        }
        missing_entries = [
            entry for entry in ATTACK_GITIGNORE_ENTRIES if entry not in existing_entries
        ]
        if not missing_entries and not removed_legacy_entries:
            return
        with exclude_path.open("w", encoding="utf-8") as handle:
            for line in filtered_lines:
                handle.write(f"{line}\n")
            for entry in missing_entries:
                handle.write(f"{entry}\n")

    def clone_repository(self, clone_url: str, destination: str = "/workspace") -> None:
        _ = destination
        workspace_path = Path(
            getattr(self, "_workspace_path", Path(getattr(self, "_repo_cwd", ".")))
        )
        git_url = self._configure_git_url_with_token(clone_url)
        existing_repo_cwd = self._discover_existing_repo_cwd()
        if existing_repo_cwd is not None:
            self._repo_cwd = Path(existing_repo_cwd)
            self._env = build_workspace_git_env(self._repo_cwd, materialize=True)
            self._set_origin_url(git_url)
            self._configure_repo_git_identity()
            self._ensure_attack_gitignore_entries()
            return

        self._run_in_container(
            ["git", "clone", "--depth", "1", git_url, str(workspace_path)],
            cwd=str(workspace_path.parent),
            check=True,
        )
        self._repo_cwd = workspace_path
        self._env = build_workspace_git_env(self._repo_cwd, materialize=True)
        self._set_origin_url(git_url)
        self._configure_repo_git_identity()
        self._ensure_attack_gitignore_entries()

    def set_git_token(self, token: str | None) -> None:
        self._git_token = token

    def checkout_branch(self, branch_name: str) -> None:
        result = self.run_git(["checkout", "-b", branch_name], check=False)
        if result.returncode != 0:
            self.run_git(["checkout", "-b", branch_name, "origin/main"], check=True)

    def run_git(
        self, args: list[str], *, check: bool = True
    ) -> subprocess.CompletedProcess:
        return self._run_in_container(
            self._git_command(args, cwd=self._repo_cwd),
            cwd=str(self._repo_cwd),
            check=check,
        )

    def read_file(self, relative_path: str) -> str | None:
        target_path = self._repo_cwd / relative_path
        if not target_path.exists():
            return None
        return target_path.read_text(encoding="utf-8")

    def commit_and_push(
        self,
        branch: str,
        commit_message: str = "Add temporary change",
        exclude_paths: list[str] | None = None,
        include_paths: list[str] | None = None,
    ) -> bool:
        if include_paths is None:
            self.run_git(["add", "-A"], check=False)
            if exclude_paths:
                self.run_git(["reset", "--", *exclude_paths], check=False)
        else:
            for path in include_paths:
                self.run_git(["add", "-A", "--", path], check=False)

        status = self.run_git(
            ["status", "--porcelain", "--untracked-files=no"], check=False
        )
        if not status.stdout.strip():
            return False

        self.run_git(["commit", "-m", commit_message], check=False)
        push_result = self.run_git(["push", "origin", branch, "--force"], check=False)
        return push_result.returncode == 0

    def stop(self) -> None:
        return None

    def remove(self) -> None:
        return None

    def _git_command(self, args: list[str], *, cwd: Path | None = None) -> list[str]:
        safe_directory = Path(cwd or self._repo_cwd).resolve()
        return ["git", "-c", f"safe.directory={safe_directory}", *args]


# Backward-compatible name expected by imports/tests.
class RepositorySandbox(HostRepositorySandbox):
    pass


class SandboxManager:
    def __init__(self, base_name: str = "pwn-hunter-sandbox", use_host: bool = False):
        _ = base_name
        if not use_host:
            LOGGER.warning(
                "Docker sandbox mode is removed; falling back to host-only mode."
            )

    def create_sandbox(
        self,
        repository_name: str,
        workspace_path: Path,
        git_token: str | None = None,
        git_user_email: str = DEFAULT_GIT_USER_EMAIL,
        git_user_name: str = DEFAULT_GIT_USER_NAME,
    ) -> RepositorySandbox:
        _ = repository_name
        sandbox = RepositorySandbox(workspace_path)
        sandbox.start(
            workspace_path,
            git_token=git_token,
            git_user_email=git_user_email,
            git_user_name=git_user_name,
        )
        sandbox.set_git_token(git_token)
        return sandbox

    def cleanup_all(self) -> None:
        return None


def _redact_sensitive_text(value: str) -> str:
    redacted = re.sub(
        r"x-access-token:[^@]+@github\.com",
        "x-access-token:***@github.com",
        value,
    )
    redacted = re.sub(r"\bgh[pousr]_[A-Za-z0-9_]+\b", "***", redacted)
    return redacted
